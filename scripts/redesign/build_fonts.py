#!/usr/bin/env python3
"""Bake the Redesign's runtime fonts into C arrays (components/seedsigner/redesign/fonts/).

LVGL's tiny_ttf (stb_truetype) rasterizes TrueType outlines at any pixel size, which is
what lets the Redesign scale its type with the screen. Two sources need preparing:

  - seedsigner-icons.otf  is CFF (cubic) outlines, which stb_truetype cannot read, so the
                          PUA icon range is converted to TrueType (quadratic) outlines.
  - Inconsolata-SemiBold  is subset to printable ASCII + the few symbols the UI uses.

Open Sans is NOT baked here: the Redesign reuses the engine's compiled-in OpenSans Western
subsets (components/seedsigner/fonts/opensans_western_*.c).

Run after changing a source font in components/seedsigner/redesign/fonts/src/:

    python3 -m pip install fonttools
    python3 scripts/redesign/build_fonts.py
"""
import io
import os

from fontTools import subset
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont, newTable

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FONTS = os.path.join(REPO, "components", "seedsigner", "redesign", "fonts")
SRC = os.path.join(FONTS, "src")

ICON_RANGE = list(range(0xE900, 0xE924))                 # SS_ICON codepoints in the prototype
MONO_RANGE = list(range(0x20, 0x7F)) + [0xB7, 0x2026]    # ASCII, middle dot, ellipsis


def subset_font(font, codepoints):
    opts = subset.Options()
    opts.layout_features = ["*"]
    opts.notdef_outline = True
    opts.hinting = False
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=codepoints)
    sub.subset(font)


def cff_to_truetype(font):
    """Replace a font's CFF table with glyf/loca (quadratic) outlines."""
    order = font.getGlyphOrder()
    gs = font.getGlyphSet()
    glyf = newTable("glyf")
    glyf.glyphOrder = order
    glyf.glyphs = {}
    for name in order:
        pen = TTGlyphPen(gs)
        gs[name].draw(Cu2QuPen(pen, max_err=1.0, reverse_direction=True))
        glyf.glyphs[name] = pen.glyph()
    font["glyf"] = glyf
    font["loca"] = newTable("loca")
    font["maxp"] = newTable("maxp")
    font["maxp"].tableVersion = 0x00010000
    for attr in ("maxZones", "maxTwilightPoints", "maxStorage", "maxFunctionDefs",
                 "maxInstructionDefs", "maxStackElements", "maxSizeOfInstructions",
                 "maxComponentElements"):
        setattr(font["maxp"], attr, 0)
    font["maxp"].maxZones = 1
    font["head"].glyphDataFormat = 0
    font["head"].indexToLocFormat = 0
    font["post"].formatType = 2.0
    font["post"].extraNames = []
    font["post"].mapping = {}
    del font["CFF "]
    if "VORG" in font:
        del font["VORG"]
    font.sfntVersion = "\x00\x01\x00\x00"
    font.recalcBBoxes = True


def write_c(symbol, data, note):
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ",".join(str(b) for b in data[i:i + 16]) + ",")
    path = os.path.join(FONTS, f"{symbol}.c")
    with open(path, "w") as f:
        f.write(f"// Generated by scripts/redesign/build_fonts.py. Do not edit.\n// {note}\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
        f.write(f"const uint8_t {symbol}_ttf[] = {{\n" + "\n".join(rows) + "\n};\n")
        f.write(f"const size_t {symbol}_ttf_len = sizeof({symbol}_ttf);\n")
    print(f"wrote {os.path.relpath(path, REPO)} ({len(data)} bytes)")


def bake(src_name, symbol, codepoints, note, convert_cff=False):
    font = TTFont(os.path.join(SRC, src_name))
    subset_font(font, codepoints)
    if convert_cff and "CFF " in font:
        cff_to_truetype(font)
    buf = io.BytesIO()
    font.save(buf)
    write_c(symbol, buf.getvalue(), note)


def main():
    bake("seedsigner-icons.otf", "rd_icons", ICON_RANGE,
         "seedsigner-icons.otf, PUA U+E900-E923, CFF converted to TrueType outlines.",
         convert_cff=True)
    bake("Inconsolata-SemiBold.ttf", "rd_mono_semibold", MONO_RANGE,
         "Inconsolata SemiBold (OFL), printable ASCII + middle dot + ellipsis.")


if __name__ == "__main__":
    main()
